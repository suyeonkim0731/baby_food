import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx={window:{},URL};vm.runInNewContext(fs.readFileSync('dist/barcode-data.js','utf8'),ctx);const b=ctx.window.BarcodeData;
assert.ok(b.valid('3017620422003'));
assert.ok(b.valid('96385074'));
assert.ok(b.valid('036000291452'));
assert.equal(b.valid('3017620422004'),false);
assert.equal(b.valid('123'),false);
assert.equal(b.valid('<script>'),false);
assert.equal(b.normalize(' 0360-0029 1452 '),'036000291452');
assert.equal(b.imageURL('javascript:alert(1)'),'');
assert.equal(b.imageURL('https://images.openfoodfacts.org.evil.example/x.jpg'),'');
assert.equal(b.imageURL('https://user@images.openfoodfacts.org/x.jpg'),'');
assert.ok(b.imageURL('https://images.openfoodfacts.org/images/a.jpg'));
assert.equal(b.unpack({status:'failure'},'3017620422003'),null);
assert.equal(b.unpack({product:{code:'11111111'}},'3017620422003'),null);
assert.ok(b.unpack({product:{code:'0036000291452'}},'036000291452'));
const p=b.unpack({product:{code:'3017620422003',product_name:'Test',image_front_small_url:'https://evil.example/photo.jpg',nutriments:{sugars_100g:0,salt_100g:-1,proteins_100g:'10'},additives_tags:['en:e330',{}]}},'3017620422003');
assert.equal(p.name,'Test');assert.equal(p.image,'');assert.equal(p.nutrients[1].value,0);assert.equal(p.nutrients[2].value,null);assert.equal(p.nutrients[3].value,null);assert.equal(p.additives.length,1);
assert.ok(b.url('3017620422003').startsWith('https://world.openfoodfacts.org/api/v3/product/3017620422003.json?'));
assert.ok(new URL(b.url('3017620422003')).searchParams.get('User-Agent').includes('AdditiveNote'));
console.log('PASS: GTIN formats, checksums, leading zeroes, invalid input, safe image URLs, missing products and nutrient zero vs missing.');
