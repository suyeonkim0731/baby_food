import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('dist/data.js','utf8'),context);
vm.runInNewContext(fs.readFileSync('dist/additives.js','utf8'),context);
const a=context.window.AdditiveNote,foods=context.window.FOOD_DATA;
assert.equal(a.analyze(['쌀']).count,0);
assert.equal(a.analyze([]).count,0);
assert.equal(a.analyze(['처음 보는 이름']).unresolved.length,1);
assert.equal(a.analyze(['혼합제제']).unresolved[0],'혼합제제');
assert.equal(a.analyze(['구연산','구연산']).count,1);
assert.equal(a.analyze(['구연산','구연산칼륨']).count,2);
assert.equal(a.analyze(['구연산','구연산칼륨','폴리인산나트륨']).count,3);
assert.equal(a.fromText('구연산칼륨').count,1);
assert.equal(a.fromText('구연산철암모늄').entries[0].name,'구연산철암모늄');
assert.equal(a.fromText('구연산칼륨추출물').count,0);
assert.equal(a.fromText('구 연 산 칼 륨, 인산삼나트륨').count,2);
assert.equal(a.analyze(['구연산','혼합제제']).unresolved.length,1);
assert.equal(a.product({candidates:[{ingredients:['구연산']},{ingredients:['쌀']}]}).candidateDifference,true);
assert.ok(!a.panel(a.analyze(['<img src=x onerror=alert(1)>'])).includes('<img'));
assert.ok(a.panel(a.analyze(['구연산'])).includes('noopener noreferrer'));
assert.equal(a.analyze(foods.find(p=>p.name==='앙팡 유기농 아기치즈 2단계').candidates[0].ingredients).count,2);
assert.equal(a.analyze(foods.find(p=>p.name==='맘마밀 안심소스 로제치킨카레').candidates[0].ingredients).count,1);
assert.equal(a.purposeLabel(a.find('구연산철암모늄')),'영양 보충용');
assert.equal(a.purposeLabel(a.find('구연산')),'산도 조절용');
assert.equal(a.purposeLabel(a.find('폴리인산나트륨')),'산도 조절용 · 부풀림용');
assert.equal(a.purposes(a.analyze(['구연산','구연산칼륨'])).length,2);
assert.ok(a.explanation(a.find('구연산철암모늄')).includes('공식 용도명 · 영양강화제'));
assert.ok(a.panel(a.analyze(['구연산'])).includes('산도 조절용'));
assert.ok(!/signal-|파랑|노랑|빨강/.test(a.panel(a.analyze(['구연산','구연산칼륨','폴리인산나트륨']))));
assert.ok(!a.badge(a.product({candidates:[{ingredients:['구연산']},{ingredients:['쌀']}]})).includes('산도 조절용'));
assert.ok(!/signal-|파랑|노랑|빨강/.test(fs.readFileSync('dist/index.html','utf8')));
console.log('PASS: purpose labels, multiple roles, official terminology, neutral counts, unknowns, matching, candidate differences, escaping and real records.');
